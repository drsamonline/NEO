//! Making a project's dependencies importable.
//!
//! `nova.toml` can name a dependency three ways: a local `path`, a `git` URL, or a
//! bare `version`. The first two are resolved here into a directory the compiler is
//! told to search with `--module-root`; the third is not, and says so.
//!
//! # Why this shells out to `git`
//!
//! Because the alternative is an HTTP client, and this crate used to have one: it
//! served a mocked registry, reached a host that does not exist, and dragged in the
//! only non-permissive licence in the tree. `git` is already installed on any machine
//! that has source to fetch, it honours the user's own configuration and credentials,
//! and it means the package manager still contains no network code.
//!
//! # What this does not do
//!
//! No version solving across a dependency graph — a dependency's own dependencies are
//! not fetched. No lockfile yet. No registry. Each of those is named where it is
//! missing rather than implied.

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::commands::CommandError;
use crate::manifest::{DependencySpec, Manifest};

/// Where fetched git dependencies live, relative to the project.
///
/// `.nova/` rather than `nova_modules/`: that name is already used by the older
/// registry commands, which write dependency *metadata* there. Mixing fetched source
/// into it would make `git clone` fail on a directory that is not empty.
const DEPENDENCY_DIR: &str = ".nova/deps";

/// One dependency, resolved to a directory on disk.
#[derive(Debug, Clone)]
pub struct Resolved {
    pub name: String,
    /// The directory to hand to the compiler as a module root.
    pub root: PathBuf,
    /// What it was resolved from, for a message a human can act on.
    pub source: String,
}

/// The lock file, so two machines resolve the same manifest to the same commits.
///
/// Without it, a `git` dependency with a `branch` — or with no pin at all — resolved to whatever
/// the branch pointed at that day. `DEV_PLAN.md` said so plainly: "two machines can currently
/// resolve the same `nova.toml` to different revisions".
///
/// The format is one line per pinned dependency, sorted by name:
///
/// ```text
/// # nova.lock — generated by `nova-pkg`. Commit this file.
/// util https://example.invalid/util.git 3f2a1b9c…
/// ```
///
/// A `path` dependency is not pinned: its content is the directory, not a revision.
const LOCK_FILE: &str = "nova.lock";

#[derive(Debug, Default)]
struct Lock {
    /// name -> (url, commit)
    pins: std::collections::BTreeMap<String, (String, String)>,
}

impl Lock {
    fn read(project: &Path) -> Lock {
        let path = project.join(LOCK_FILE);
        let mut pins = std::collections::BTreeMap::new();
        let Ok(text) = std::fs::read_to_string(&path) else {
            return Lock { pins };
        };
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut parts = line.split_whitespace();
            if let (Some(name), Some(url), Some(commit)) =
                (parts.next(), parts.next(), parts.next())
            {
                pins.insert(name.to_string(), (url.to_string(), commit.to_string()));
            }
        }
        Lock { pins }
    }

    fn write(&self, project: &Path) -> Result<(), CommandError> {
        let mut text = String::from(
            "# nova.lock — generated by `nova-pkg`. Commit this file: it is what makes a\n\
             # build reproducible. A `path` dependency is not listed; its content is the\n\
             # directory, not a revision.\n",
        );
        for (name, (url, commit)) in &self.pins {
            text.push_str(&format!("{name} {url} {commit}\n"));
        }
        std::fs::write(project.join(LOCK_FILE), text)?;
        Ok(())
    }

    /// The commit a lock pins, when it pins this name at this url.
    ///
    /// A changed url is not the same dependency, so the pin does not apply and the dependency is
    /// resolved afresh rather than checked out at a commit from a different repository.
    fn pin(&self, name: &str, url: &str) -> Option<&str> {
        self.pins
            .get(name)
            .filter(|(pinned_url, _)| pinned_url == url)
            .map(|(_, commit)| commit.as_str())
    }
}

/// Resolve every dependency to a directory, fetching the git ones.
///
/// Returns them in name order so two runs on the same manifest produce the same
/// `--module-root` arguments.
pub fn resolve(manifest: &Manifest, project: &Path) -> Result<Vec<Resolved>, CommandError> {
    let mut lock = Lock::read(project);
    let deps_dir = project.join(DEPENDENCY_DIR);
    // One flat namespace, the same rule the language has (ADR 0019): a name must mean one thing,
    // so a second dependency with the same name is accepted only if it resolves to the same place.
    let mut seen: std::collections::BTreeMap<String, String> = std::collections::BTreeMap::new();
    let mut resolved = Vec::new();
    let mut wrote_pin = false;
    resolve_graph(
        manifest,
        project,
        &deps_dir,
        &mut lock,
        &mut seen,
        &mut resolved,
        &mut wrote_pin,
        0,
    )?;
    // Only written when there is something to pin, so a project with path dependencies only
    // does not acquire a lock file it has no use for.
    if wrote_pin {
        lock.write(project)?;
    }
    resolved.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(resolved)
}

/// Walk the dependency graph, not just its first level.
///
/// `DEV_PLAN.md` named this as the other half of the package manager's gap: "a transitive graph,
/// so a dependency's own dependencies are still invisible". A dependency that has a `Nova.toml`
/// of its own is resolved the same way the root project is, and everything it pulls in lands in
/// the root project's `.nova/deps` — one flat directory, because the compiler takes module roots
/// and NOVA has one namespace.
///
/// Two things follow from that, and both are errors rather than silent choices:
///
/// - **a cycle** stops at the point where a name is already resolved, because a second visit with
///   the same source is not new work;
/// - **a name used twice for different things** is refused, naming both sources, because the
///   compiler could only pick one.
#[allow(clippy::too_many_arguments)]
fn resolve_graph(
    manifest: &Manifest,
    relative_to: &Path,
    deps_dir: &Path,
    lock: &mut Lock,
    seen: &mut std::collections::BTreeMap<String, String>,
    resolved: &mut Vec<Resolved>,
    wrote_pin: &mut bool,
    depth: usize,
) -> Result<(), CommandError> {
    // A dependency graph deeper than this is a mistake rather than a program; the limit turns a
    // pathological manifest into a message instead of a stack overflow.
    const MAX_DEPTH: usize = 16;
    if depth > MAX_DEPTH {
        return Err(CommandError::BuildFailed(format!(
            "dependency graph is more than {MAX_DEPTH} levels deep at `{}` — is there a cycle \
             through path dependencies?",
            relative_to.display()
        )));
    }

    let mut names: Vec<&String> = manifest.dependencies.keys().collect();
    names.sort();

    for name in names {
        let spec = &manifest.dependencies[name];
        let (entry, pin) = resolve_one(name, spec, relative_to, deps_dir, lock)?;
        if let Some((url, commit)) = pin {
            lock.pins.insert(name.clone(), (url, commit));
            *wrote_pin = true;
        }

        if let Some(existing) = seen.get(name) {
            if existing != &entry.source {
                return Err(CommandError::BuildFailed(format!(
                    "two dependencies are named `{name}`: one from {}, another from {}. \
                     NOVA has one flat namespace, so a name has to mean one thing — rename one \
                     of them.",
                    existing, entry.source
                )));
            }
            // Already resolved, and to the same place. This is also where a cycle stops.
            continue;
        }
        seen.insert(name.clone(), entry.source.clone());

        let root = entry.root.clone();
        resolved.push(entry);

        // A dependency with its own manifest brings its own dependencies.
        if root.join("Nova.toml").is_file() {
            let inner = crate::manifest::load_manifest(&root).map_err(|error| {
                CommandError::BuildFailed(format!(
                    "dependency `{name}` has a Nova.toml that cannot be read: {error}"
                ))
            })?;
            resolve_graph(
                &inner, &root, deps_dir, lock, seen, resolved, wrote_pin, depth + 1,
            )?;
        }
    }
    Ok(())
}

fn resolve_one(
    name: &str,
    spec: &DependencySpec,
    // The directory of the manifest that declared this dependency: a `path` is relative to it,
    // which is not the root project once the graph is deeper than one level.
    relative_to: &Path,
    // Where fetched git dependencies live. Always the *root* project's `.nova/deps`, so a
    // transitive dependency is not buried inside its parent's checkout.
    deps_dir: &Path,
    lock: &Lock,
) -> Result<(Resolved, Option<(String, String)>), CommandError> {
    let details = match spec {
        DependencySpec::Detailed(details) => details,
        DependencySpec::Simple(version) => {
            return Err(registry_error(name, version));
        }
    };

    if let Some(path) = &details.path {
        let root = normalise(&relative_to.join(path));
        if !root.is_dir() {
            return Err(CommandError::BuildFailed(format!(
                "dependency `{name}` points at {}, which is not a directory",
                root.display()
            )));
        }
        let source = format!("path {}", root.display());
        // A path dependency is not pinned: its content is the directory, not a revision.
        return Ok((
            Resolved {
                name: name.to_string(),
                root,
                source,
            },
            None,
        ));
    }

    if let Some(url) = &details.git {
        let root = deps_dir.join(name);
        // A pin from `nova.lock` wins over the manifest's `rev`/`tag`/`branch`: that is the
        // whole point of a lock file, and a build that quietly used the branch instead would
        // be the non-reproducibility this file exists to remove.
        let pinned = lock.pin(name, url).map(|commit| commit.to_string());
        let commit = fetch(name, url, details, &root, pinned.as_deref())?;
        let source = match &pinned {
            Some(commit) => format!("git {url} (locked at {})", &commit[..7.min(commit.len())]),
            None => format!("git {url}"),
        };
        return Ok((
            Resolved {
                name: name.to_string(),
                root,
                source,
            },
            Some((url.clone(), commit)),
        ));
    }

    let version = details.version.clone().unwrap_or_else(|| "*".to_string());
    Err(registry_error(name, &version))
}

/// The one message for a dependency that needs a registry.
fn registry_error(name: &str, version: &str) -> CommandError {
    CommandError::BuildFailed(format!(
        "cannot resolve `{name} = \"{version}\"`: the NOVA registry is not implemented, \
         so a version-only dependency cannot be fetched.\n\
         Use a path or a git dependency instead:\n    \
         {name} = {{ path = \"../{name}\" }}\n    \
         {name} = {{ git = \"https://github.com/you/{name}\" }}"
    ))
}

/// Clone or update a git dependency into `root`.
fn fetch(
    name: &str,
    url: &str,
    details: &crate::manifest::DependencyDetails,
    root: &Path,
    pinned: Option<&str>,
) -> Result<String, CommandError> {
    // A pinned commit is what to check out; otherwise the manifest's own reference, and
    // failing that whatever the clone lands on.
    let wanted = pinned.map(|commit| commit.to_string()).or_else(|| {
        details
            .rev
            .clone()
            .or_else(|| details.tag.clone())
            .or_else(|| details.branch.clone())
    });

    if !root.join(".git").exists() {
        if let Some(parent) = root.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let mut clone = Command::new("git");
        clone.arg("clone").arg("--depth").arg("1");
        // `--branch` accepts a branch or a tag, not a commit — and a pinned commit must not be
        // passed to it, so the shallow clone takes the default branch and the checkout below
        // moves to the pin.
        if pinned.is_none() {
            if let Some(reference) = details.tag.as_ref().or(details.branch.as_ref()) {
                clone.arg("--branch").arg(reference);
            }
        }
        clone.arg(url).arg(root);
        run(name, &mut clone)?;
    }

    // A revision is not something `clone --depth 1` can check out, so it is fetched
    // explicitly. A no-op when the clone already landed on it.
    if let Some(reference) = &wanted {
        // A shallow clone holds one commit; a pin from another day is not in it. Ask for the
        // commit by name before checking it out, or the checkout fails on a repository that
        // has it. `--depth 1` plus an explicit fetch keeps the clone small.
        let mut has = Command::new("git");
        has.arg("-C").arg(root).arg("cat-file").arg("-e").arg(format!("{reference}^{{commit}}"));
        let present = has.output().map(|out| out.status.success()).unwrap_or(false);
        if !present {
            let mut fetch_it = Command::new("git");
            fetch_it.arg("-C").arg(root).arg("fetch").arg("--depth").arg("1").arg("origin").arg(reference);
            // A commit some server refuses to serve by sha is a real failure; a branch that the
            // clone already has is not, so only the checkout below decides.
            let _ = run(name, &mut fetch_it);
        }
        let mut checkout = Command::new("git");
        checkout.arg("-C").arg(root).arg("checkout").arg(reference);
        run(name, &mut checkout)?;
    }

    // The commit actually checked out is what the lock records, so a later run pins this one
    // rather than whatever the branch does next.
    let mut head = Command::new("git");
    head.arg("-C").arg(root).arg("rev-parse").arg("HEAD");
    let output = head.output().map_err(|error| {
        CommandError::BuildFailed(format!("could not ask git for the commit of `{name}`: {error}"))
    })?;
    if !output.status.success() {
        return Err(CommandError::BuildFailed(format!(
            "could not read the checked-out commit of dependency `{name}`"
        )));
    }
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

/// Run a git command, turning a failure into something a user can act on.
fn run(name: &str, command: &mut Command) -> Result<(), CommandError> {
    let rendered = format!("{command:?}");
    let output = command.output().map_err(|error| {
        CommandError::BuildFailed(format!(
            "could not run `git` for dependency `{name}`: {error}\n\
             git is needed to fetch a git dependency; install it, or use a path dependency."
        ))
    })?;
    if output.status.success() {
        return Ok(());
    }
    Err(CommandError::BuildFailed(format!(
        "`{rendered}` failed for dependency `{name}`:\n{}",
        String::from_utf8_lossy(&output.stderr).trim()
    )))
}

/// Resolve `..` and `.` without requiring the path to exist yet.
fn normalise(path: &Path) -> PathBuf {
    // `canonicalize` needs the directory to exist, which is what the caller is about
    // to check; this keeps the error message readable when it does not.
    path.canonicalize().unwrap_or_else(|_| path.to_path_buf())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::{DependencyDetails, DependencySpec};

    fn manifest_with(name: &str, spec: DependencySpec) -> Manifest {
        let mut manifest: Manifest =
            toml::from_str("[package]\nname = \"demo\"\nversion = \"0.1.0\"\n")
                .expect("a minimal manifest parses");
        manifest.dependencies.insert(name.to_string(), spec);
        manifest
    }

    #[test]
    fn a_version_only_dependency_names_the_registry_as_the_problem() {
        let manifest = manifest_with("utils", DependencySpec::Simple("1.0".to_string()));
        let error = resolve(&manifest, Path::new(".")).expect_err("must fail");
        let message = error.to_string();
        assert!(message.contains("registry is not implemented"), "{message}");
        assert!(message.contains("path = "), "must suggest path: {message}");
        assert!(message.contains("git = "), "must suggest git: {message}");
    }

    #[test]
    fn a_dependencys_own_dependencies_are_resolved() {
        // `DEV_PLAN.md` called this the other half of the gap: a dependency's own dependencies
        // were invisible. A path dependency whose directory has a `Nova.toml` brings its own.
        let root = std::env::temp_dir().join(format!("nova-graph-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let project = root.join("project");
        let middle = root.join("middle");
        let leaf = root.join("leaf");
        for dir in [&project, &middle, &leaf] {
            std::fs::create_dir_all(dir).expect("dir");
        }

        // leaf <- middle <- project
        let mut inner: Manifest =
            toml::from_str("[package]\nname = \"middle\"\nversion = \"0.1.0\"\n")
                .expect("a minimal manifest parses");
        inner.dependencies.insert(
            "leaf".to_string(),
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../leaf")),
                ..DependencyDetails::default()
            }),
        );
        std::fs::write(
            middle.join("Nova.toml"),
            toml::to_string_pretty(&inner).expect("serialise"),
        )
        .expect("write middle manifest");

        let outer = manifest_with(
            "middle",
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../middle")),
                ..DependencyDetails::default()
            }),
        );

        let resolved = resolve(&outer, &project).expect("the graph resolves");
        let names: Vec<&str> = resolved.iter().map(|entry| entry.name.as_str()).collect();
        assert_eq!(names, vec!["leaf", "middle"], "got {names:?}");
    }

    #[test]
    fn one_name_for_two_places_is_refused() {
        // The flat-namespace rule the language has (ADR 0019), applied to packages: the compiler
        // takes module roots and cannot pick between two `utils`.
        let root = std::env::temp_dir().join(format!("nova-clash-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let project = root.join("project");
        let one = root.join("one");
        let two = root.join("two");
        for dir in [&project, &one, &two] {
            std::fs::create_dir_all(dir).expect("dir");
        }

        // Named apart from the directory `middle`: a manifest called `middle` shadowed the
        // `PathBuf` of the same name, and `middle.join(..)` then failed to compile.
        let mut middle_manifest: Manifest =
            toml::from_str("[package]\nname = \"middle\"\nversion = \"0.1.0\"\n")
                .expect("a minimal manifest parses");
        middle_manifest.dependencies.insert(
            "utils".to_string(),
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../two")),
                ..DependencyDetails::default()
            }),
        );
        std::fs::write(
            middle.join("Nova.toml"),
            toml::to_string_pretty(&middle_manifest).expect("serialise"),
        )
        .expect("write");

        let mut outer = manifest_with(
            "utils",
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../one")),
                ..DependencyDetails::default()
            }),
        );
        outer.dependencies.insert(
            "middle".to_string(),
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../middle")),
                ..DependencyDetails::default()
            }),
        );

        let error = resolve(&outer, &project).expect_err("two utils must be refused");
        let message = format!("{error}");
        assert!(
            message.contains("two dependencies are named `utils`"),
            "the error should name the clash; got {message}"
        );
    }

    #[test]
    fn a_git_dependency_is_pinned_and_the_pin_is_reused() {
        // The defect this file exists to remove: a `git` dependency with no pin resolved to
        // whatever the branch pointed at that day, so two machines could build different code
        // from one manifest. The test moves the branch between the two resolves — a lock file
        // that is not consulted would follow it.
        let root = std::env::temp_dir().join(format!("nova-lock-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let project = root.join("project");
        let upstream = root.join("upstream");
        std::fs::create_dir_all(&project).expect("project");
        std::fs::create_dir_all(&upstream).expect("upstream");

        let git = |args: &[&str], dir: &Path| {
            let out = Command::new("git")
                .args(args)
                .current_dir(dir)
                .output()
                .expect("git runs");
            assert!(
                out.status.success(),
                "git {args:?} failed: {}",
                String::from_utf8_lossy(&out.stderr)
            );
            String::from_utf8_lossy(&out.stdout).trim().to_string()
        };

        git(&["init", "-q"], &upstream);
        git(&["config", "user.email", "test@example.invalid"], &upstream);
        git(&["config", "user.name", "test"], &upstream);
        std::fs::write(upstream.join("lib.nova"), "fn one() -> int { 1 }\n").expect("write");
        git(&["add", "."], &upstream);
        git(&["commit", "-qm", "first"], &upstream);
        let first = git(&["rev-parse", "HEAD"], &upstream);

        let manifest = manifest_with(
            "utils",
            DependencySpec::Detailed(DependencyDetails {
                git: Some(upstream.display().to_string()),
                ..DependencyDetails::default()
            }),
        );

        let resolved = resolve(&manifest, &project).expect("a git dependency resolves");
        assert_eq!(resolved.len(), 1);
        let lock = std::fs::read_to_string(project.join("nova.lock")).expect("a lock file is written");
        assert!(
            lock.contains(&first),
            "the lock should pin the commit that was checked out; got:\n{lock}"
        );

        // Move the branch upstream. A second resolve must stay on the pinned commit.
        std::fs::write(upstream.join("lib.nova"), "fn one() -> int { 2 }\n").expect("write");
        git(&["add", "."], &upstream);
        git(&["commit", "-qm", "second"], &upstream);
        let second = git(&["rev-parse", "HEAD"], &upstream);
        assert_ne!(first, second);

        let again = resolve(&manifest, &project).expect("resolves again");
        let checked_out = git(&["rev-parse", "HEAD"], &again[0].root);
        assert_eq!(
            checked_out, first,
            "the second resolve followed the branch instead of the lock"
        );
        assert!(
            again[0].source.contains("locked at"),
            "the source line should say it used the pin; got {}",
            again[0].source
        );
    }

    #[test]
    fn a_path_dependency_resolves_to_its_directory() {
        let root = std::env::temp_dir().join(format!("nova-deps-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let project = root.join("project");
        let dependency = root.join("utils");
        std::fs::create_dir_all(&project).expect("project");
        std::fs::create_dir_all(&dependency).expect("dependency");

        let manifest = manifest_with(
            "utils",
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("../utils")),
                ..DependencyDetails::default()
            }),
        );

        let resolved = resolve(&manifest, &project).expect("a path dependency resolves");
        assert_eq!(resolved.len(), 1);
        assert_eq!(resolved[0].name, "utils");
        assert!(resolved[0].root.ends_with("utils"), "{:?}", resolved[0].root);

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn a_path_dependency_that_does_not_exist_says_which_path() {
        let manifest = manifest_with(
            "missing",
            DependencySpec::Detailed(DependencyDetails {
                path: Some(PathBuf::from("./nowhere")),
                ..DependencyDetails::default()
            }),
        );
        let error = resolve(&manifest, Path::new("/tmp")).expect_err("must fail");
        let message = error.to_string();
        assert!(message.contains("`missing`"), "{message}");
        assert!(message.contains("nowhere"), "must name the path: {message}");
    }
}
