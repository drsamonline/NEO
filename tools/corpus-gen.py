#!/usr/bin/env python3
"""Generate NOVA programs, and the output they must produce.

The differential harness in `nova-compiler test --parity` compares the four
backends against each other. That catches a backend that disagrees — it cannot
catch four backends that agree and are all wrong. So every generated program
comes with a `.expected` file holding the output computed *here*, in Python,
independently of the compiler. `test --parity` reads a `.expected` sidecar when it
exists and checks the C reference against it too, which turns agreement into
conformance.

The generated subset is deliberately narrow: integers, `+`/`-`, comparison,
`if`/`else`, `while`, function calls, `print` of an int, and `return`. That is the
intersection every backend claims, so a failure here is a compiler bug rather
than a known limitation, and the corpus stays useful as the backends grow.

No `/` or `%`: integer division rounds differently across C, JavaScript and Rust,
and a corpus that has to special-case its own arithmetic teaches nothing. No
multiplication, for the same reason in reverse — it overflows and the backends
disagree about what overflow means.

Usage:
    tools/corpus-gen.py --out DIR [--count N] [--seed-base S]
    tools/corpus-gen.py --dump SEED        # print one program and its output
"""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

# Every value the generator can produce stays inside this, so no backend has to
# decide what integer overflow means.
MAX_STEP = 40
MAX_STRAIGHT_LINE = 12
MAX_LOOP = 20
BOUND = (MAX_STRAIGHT_LINE + MAX_LOOP + 4) * MAX_STEP


def mix(a: int, b: int) -> int:
    """The reference semantics of the generated `mix`."""
    return a - b if a > b else a + b


def triangle(n: int) -> int:
    """The reference semantics of the generated `triangle`."""
    total = 0
    j = 0
    while j < n:
        total += j
        j += 1
    return total


def build(seed: int) -> tuple[str, str]:
    """Return (source, expected stdout) for one seed."""
    rng = random.Random(seed)
    straight = [rng.randint(1, MAX_STEP) for _ in range(rng.randint(1, MAX_STRAIGHT_LINE))]
    loop_step = rng.randint(1, MAX_STEP)
    loop_count = rng.randint(0, MAX_LOOP)

    lines = [
        f"// Generated by tools/corpus-gen.py — seed {seed}.",
        "// Do not edit: regenerate with the same seed to get this file back.",
        "",
        "fn mix(a: int, b: int) -> int {",
        "    if a > b {",
        "        return a - b;",
        "    } else {",
        "        return a + b;",
        "    }",
        "}",
        "",
        "fn triangle(n: int) -> int {",
        "    let mut t = 0;",
        "    let mut j = 0;",
        "    while j < n {",
        "        t = t + j;",
        "        j = j + 1;",
        "    }",
        "    return t;",
        "}",
        "",
        "fn main() -> int {",
        "    let mut acc = 0;",
    ]

    printed = []
    acc = 0
    for step in straight:
        lines += [f"    acc = mix(acc, {step});", "    print(acc);"]
        acc = mix(acc, step)
        printed.append(str(acc))

    lines += [
        "    let mut i = 0;",
        f"    while i < {loop_count} {{",
        f"        acc = mix(acc, {loop_step});",
        "        print(acc);",
        "        i = i + 1;",
        "    }",
    ]
    for _ in range(loop_count):
        acc = mix(acc, loop_step)
        printed.append(str(acc))

    lines += [f"    print(triangle({loop_count}));", "    return 0;", "}", ""]
    printed.append(str(triangle(loop_count)))

    source = "\n".join(lines)

    # The guard that makes the subset safe: if any value escaped the bound, the
    # generator would be producing a program whose meaning depends on overflow.
    for value in printed:
        if abs(int(value)) > BOUND:
            raise SystemExit(f"seed {seed}: value {value} exceeded the bound {BOUND}")

    return source, "\n".join(printed) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", help="directory to write programs into")
    parser.add_argument("--count", type=int, default=20)
    parser.add_argument("--seed-base", type=int, default=1)
    parser.add_argument("--dump", type=int, help="print one program and its expected output")
    args = parser.parse_args()

    if args.dump is not None:
        source, expected = build(args.dump)
        print(source)
        print("--- expected ---")
        print(expected, end="")
        return 0

    if not args.out:
        parser.error("--out is required unless --dump is used")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    written = 0
    for seed in range(args.seed_base, args.seed_base + args.count):
        source, expected = build(seed)
        stem = f"g{seed:05d}"
        (out / f"{stem}.nova").write_text(source)
        (out / f"{stem}.expected").write_text(expected)
        written += 1

    print(f"wrote {written} program(s) to {out} (seeds {args.seed_base}..{args.seed_base + args.count - 1})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
