//! The NOVA runtime shim for generated C.
//!
//! Generated code does not call `printf` and friends directly: it includes
//! `nova_runtime.h` and calls the small, stable ABI declared there. The
//! compiler writes both files beside the generated C, and `build`/`run` link
//! `nova_runtime.c` into the executable.
//!
//! Keeping the ABI in one place is what lets the runtime grow (allocation,
//! strings, bounds checks) without changing what backends emit.

/// Name of the generated header, relative to the generated C.
pub const HEADER_FILE: &str = "nova_runtime.h";

/// Name of the generated C implementation, relative to the generated C.
pub const SOURCE_FILE: &str = "nova_runtime.c";

/// The runtime ABI: everything generated C is allowed to call.
pub const HEADER: &str = r#"/* nova_runtime.h - NOVA runtime shim (ABI v1).
 *
 * Generated by the NOVA compiler together with the program's C. Do not edit by
 * hand: regenerate by compiling again. See compiler/src/runtime.rs.
 */
#ifndef NOVA_RUNTIME_H
#define NOVA_RUNTIME_H

#include <stdbool.h>

#ifdef __cplusplus
extern "C" {
#endif

/* Output. Each writes a value with no trailing newline; the compiler emits
 * nova_print_newline() when a NOVA print/println statement ends. */
void nova_print_int(long long value);
void nova_print_float(double value);
void nova_print_bool(bool value);
void nova_print_char(char value);
void nova_print_str(const char *value);
void nova_print_newline(void);

/* Runtime version, ABI v1. */
const char *nova_runtime_version(void);

#ifdef __cplusplus
}
#endif

#endif /* NOVA_RUNTIME_H */
"#;

/// The implementation linked into every NOVA executable.
pub const SOURCE: &str = r#"/* nova_runtime.c - NOVA runtime shim (ABI v1).
 *
 * Generated by the NOVA compiler. Link this file with the generated C, or let
 * `nova-compiler build` do it.
 */
#include "nova_runtime.h"

#include <stdio.h>

void nova_print_int(long long value) {
    printf("%lld", value);
}

void nova_print_float(double value) {
    printf("%g", value);
}

void nova_print_bool(bool value) {
    fputs(value ? "true" : "false", stdout);
}

void nova_print_char(char value) {
    fputc((int)value, stdout);
}

void nova_print_str(const char *value) {
    fputs(value != NULL ? value : "(null)", stdout);
}

void nova_print_newline(void) {
    fputc('\n', stdout);
}

const char *nova_runtime_version(void) {
    return "1";
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    /// Every function the backend can emit must be declared in the header and
    /// defined in the source; a typo would otherwise surface only at link time.
    #[test]
    fn header_declares_every_print_function() {
        for kind in ["int", "float", "bool", "char", "str"] {
            let name = format!("nova_print_{kind}");
            assert!(HEADER.contains(&format!("void {name}(")), "header misses {name}");
            assert!(SOURCE.contains(&format!("void {name}(")), "source misses {name}");
        }
        for name in ["nova_print_newline", "nova_runtime_version"] {
            assert!(HEADER.contains(name), "header misses {name}");
            assert!(SOURCE.contains(name), "source misses {name}");
        }
    }
}
