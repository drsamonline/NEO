//! The NOVA runtime shim for generated C.
//!
//! Generated code does not call `printf` and friends directly: it includes
//! `nova_runtime.h` and calls the small, stable ABI declared there. The
//! compiler writes both files beside the generated C, and `build`/`run` link
//! `nova_runtime.c` into the executable.
//!
//! Keeping the ABI in one place is what lets the runtime grow (allocation,
//! strings, bounds checks) without changing what backends emit.

/// Name of the generated header, relative to the generated C.
pub const HEADER_FILE: &str = "nova_runtime.h";

/// Name of the generated C implementation, relative to the generated C.
pub const SOURCE_FILE: &str = "nova_runtime.c";

/// The runtime ABI: everything generated C is allowed to call.
pub const HEADER: &str = r#"/* nova_runtime.h - NOVA runtime shim (ABI v2).
 *
 * Generated by the NOVA compiler together with the program's C. Do not edit by
 * hand: regenerate by compiling again. See compiler/src/runtime.rs.
 */
#ifndef NOVA_RUNTIME_H
#define NOVA_RUNTIME_H

#include <stdbool.h>

#ifdef __cplusplus
extern "C" {
#endif

/* An array value: a pointer plus the length, so indexing can be checked
 * wherever the array is passed. Structs are copied by value. */
typedef struct {
    int *data;
    long long len;
} NovaArray;

/* Output. Each writes a value with no trailing newline; the compiler emits
 * nova_print_newline() when a NOVA print/println statement ends. */
void nova_print_int(long long value);
void nova_print_float(double value);
void nova_print_bool(bool value);
void nova_print_char(char value);
void nova_print_str(const char *value);
void nova_print_newline(void);

/* Strings. Functions that return `char *` return heap-allocated memory; the
 * program may free it with nova_string_free(). NULL is treated as "". */
long long nova_strlen(const char *value);
char *nova_strdup(const char *value);
char *nova_strcat(const char *left, const char *right);
long long nova_strcmp(const char *left, const char *right);
char *nova_substr(const char *value, long long start, long long length);
char *nova_tostring_int(long long value);
char *nova_tostring_bool(bool value);
void nova_string_free(char *value);

/* Arrays. Reads and writes are bounds-checked and abort on a bad index. */
long long nova_array_len(NovaArray array);
int nova_array_get(NovaArray array, long long index);
void nova_array_set(NovaArray array, long long index, int value);

/* Failure and process control. */
void nova_fail(const char *message);
void nova_panic(const char *message);
void nova_exit(long long code);
long long nova_unsupported(const char *name);

/* Runtime version, ABI v2. */
const char *nova_runtime_version(void);

#ifdef __cplusplus
}
#endif

#endif /* NOVA_RUNTIME_H */
"#;

/// The implementation linked into every NOVA executable.
pub const SOURCE: &str = r#"/* nova_runtime.c - NOVA runtime shim (ABI v2).
 *
 * Generated by the NOVA compiler. Link this file with the generated C, or let
 * `nova-compiler build` do it.
 */
#include "nova_runtime.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

void nova_print_int(long long value) {
    printf("%lld", value);
}

void nova_print_float(double value) {
    printf("%g", value);
}

void nova_print_bool(bool value) {
    fputs(value ? "true" : "false", stdout);
}

void nova_print_char(char value) {
    fputc((int)value, stdout);
}

void nova_print_str(const char *value) {
    fputs(value != NULL ? value : "(null)", stdout);
}

void nova_print_newline(void) {
    fputc('\n', stdout);
}

long long nova_strlen(const char *value) {
    return (long long)strlen(value != NULL ? value : "");
}

char *nova_strdup(const char *value) {
    const char *source = value != NULL ? value : "";
    size_t length = strlen(source);
    char *copy = (char *)malloc(length + 1);
    if (copy == NULL) {
        nova_fail("out of memory");
    }
    memcpy(copy, source, length + 1);
    return copy;
}

char *nova_strcat(const char *left, const char *right) {
    const char *a = left != NULL ? left : "";
    const char *b = right != NULL ? right : "";
    size_t a_length = strlen(a);
    size_t b_length = strlen(b);
    char *joined = (char *)malloc(a_length + b_length + 1);
    if (joined == NULL) {
        nova_fail("out of memory");
    }
    memcpy(joined, a, a_length);
    memcpy(joined + a_length, b, b_length + 1);
    return joined;
}

long long nova_strcmp(const char *left, const char *right) {
    return (long long)strcmp(left != NULL ? left : "", right != NULL ? right : "");
}

char *nova_substr(const char *value, long long start, long long length) {
    const char *source = value != NULL ? value : "";
    long long size = (long long)strlen(source);
    if (start < 0) {
        start = 0;
    }
    if (start > size || length < 0) {
        length = 0;
    }
    if (start + length > size) {
        length = size - start;
    }
    char *slice = (char *)malloc((size_t)length + 1);
    if (slice == NULL) {
        nova_fail("out of memory");
    }
    memcpy(slice, source + start, (size_t)length);
    slice[length] = '\0';
    return slice;
}

char *nova_tostring_int(long long value) {
    char buffer[32];
    snprintf(buffer, sizeof(buffer), "%lld", value);
    return nova_strdup(buffer);
}

char *nova_tostring_bool(bool value) {
    return nova_strdup(value ? "true" : "false");
}

void nova_string_free(char *value) {
    free(value);
}

long long nova_array_len(NovaArray array) {
    return array.len;
}

int nova_array_get(NovaArray array, long long index) {
    if (index < 0 || index >= array.len || array.data == NULL) {
        nova_fail("array index out of bounds");
    }
    return array.data[index];
}

void nova_array_set(NovaArray array, long long index, int value) {
    if (index < 0 || index >= array.len || array.data == NULL) {
        nova_fail("array index out of bounds");
    }
    array.data[index] = value;
}

void nova_fail(const char *message) {
    fputs("runtime error: ", stderr);
    fputs(message != NULL ? message : "unknown error", stderr);
    fputc('\n', stderr);
    exit(1);
}

void nova_panic(const char *message) {
    nova_fail(message);
}

void nova_exit(long long code) {
    exit((int)code);
}

long long nova_unsupported(const char *name) {
    fputs("runtime error: builtin not implemented: ", stderr);
    fputs(name != NULL ? name : "?", stderr);
    fputc('\n', stderr);
    exit(1);
}

const char *nova_runtime_version(void) {
    return "2";
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    /// Every function the backend can emit must be declared in the header and
    /// defined in the source; a typo would otherwise surface only at link time.
    #[test]
    fn header_and_source_declare_the_abi() {
        assert!(HEADER.contains("typedef struct {\n    int *data;\n    long long len;\n} NovaArray;"), "header must define NovaArray");
        assert!(SOURCE.contains("nova_fail(\"array index out of bounds\")"));
        assert!(HEADER.contains("ABI v2") && SOURCE.contains("ABI v2"));
    }

    #[test]
    fn header_declares_every_print_function() {
        for kind in ["int", "float", "bool", "char", "str"] {
            let name = format!("nova_print_{kind}");
            assert!(HEADER.contains(&format!("void {name}(")), "header misses {name}");
            assert!(SOURCE.contains(&format!("void {name}(")), "source misses {name}");
        }
        for name in [
            "nova_print_newline",
            "nova_runtime_version",
            "nova_strlen",
            "nova_strcat",
            "nova_strcmp",
            "nova_substr",
            "nova_array_get",
            "nova_array_set",
            "nova_array_len",
            "nova_panic",
            "nova_fail",
        ] {
            assert!(HEADER.contains(name), "header misses {name}");
            assert!(SOURCE.contains(name), "source misses {name}");
        }
    }
}
